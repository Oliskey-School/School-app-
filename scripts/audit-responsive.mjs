/**
 * Screen inventory + responsive audit -> docs/SCREEN_INVENTORY.md
 *
 * Lists every screen in the four role areas, scores its responsive risk, and
 * marks which files the current branch has already fixed, so the work can be
 * done in phases without losing track of what has been touched.
 *
 * Run: node scripts/audit-responsive.mjs
 */
import { readdirSync, statSync, readFileSync, writeFileSync, mkdirSync } from 'fs';
import { join, basename } from 'path';
import { execSync } from 'child_process';

const ROLES = ['admin', 'teacher', 'student', 'parent'];

/**
 * Only patterns that genuinely break a small viewport.
 * `grid-cols-7` is excluded on purpose: that is a calendar week.
 */
const RULES = {
    'grid-no-bp': /(?<![a-z:-])grid-cols-([3-6]|[89]|1[0-2])\b/g,
    'fixed-w': /(?<![a-z:-])(?:min-)?w-\[\s*\d{3,}px\s*\](?![^"'`]*max-w-full)/g,
    'fixed-h': /\bh-\[\s*\d{3,}px\s*\]/g,
};

const risk = (src) => {
    const h = {};
    for (const [k, re] of Object.entries(RULES)) {
        const n = (src.match(re) || []).length;
        if (n) h[k] = n;
    }
    if (/<table[\s>]/.test(src) && !/overflow-x-auto|overflow-auto|overflow-scroll/.test(src)) h['table-no-scroll'] = 1;
    if (!/\b(sm|md|lg|xl):/.test(src) && src.length > 1500) h['no-breakpoints'] = 1;
    return h;
};

function walk(d) {
    let out = [];
    for (const e of readdirSync(d)) {
        const p = join(d, e);
        if (statSync(p).isDirectory()) out = out.concat(walk(p));
        else if (p.endsWith('.tsx')) out.push(p);
    }
    return out;
}

let touched = new Set();
try {
    touched = new Set(execSync('git diff --name-only main...HEAD').toString()
        .split('\n').map(s => s.trim()).filter(Boolean));
} catch { /* not a branch off main; the column just shows "—" */ }

const out = [
    '# Screen inventory and responsive status', '',
    'Generated by `node scripts/audit-responsive.mjs`. Every `.tsx` in the four',
    'role areas is listed — nothing is filtered out.', '',
    '**Risk keys**',
    '- `grid-no-bp` — a 3+ column grid with no breakpoint, i.e. that many columns on a 390px phone.',
    '- `table-no-scroll` — a table with no horizontal scroll container, so it pushes the page sideways.',
    '- `fixed-w` / `fixed-h` — a hard pixel size that cannot shrink (`max-w-full` clears `fixed-w`).',
    '- `no-breakpoints` — a sizeable file with no responsive prefix anywhere. Often fine for a small',
    '  presentational component; worth a look for anything full-screen.',
    '',
    '`grid-cols-7` is intentionally NOT flagged: it is a calendar week and must stay seven columns.',
    '',
];

let grandFlagged = 0, grandFixed = 0, grandFiles = 0;
const summary = [];

for (const role of ROLES) {
    const files = walk(join('components', role)).sort();
    const rows = files.map(f => {
        const rel = f.replace(/\\/g, '/');
        const name = basename(f, '.tsx');
        const h = risk(readFileSync(f, 'utf8'));
        return {
            rel, name, h,
            isScreen: /Screen|Dashboard|Page|View|Modal|Portal/.test(name),
            n: Object.values(h).reduce((a, b) => a + b, 0),
            fixed: touched.has(rel),
        };
    });
    const flagged = rows.filter(r => r.n > 0).length;
    const fixed = rows.filter(r => r.fixed).length;
    grandFlagged += flagged; grandFixed += fixed; grandFiles += rows.length;
    summary.push({ role, total: rows.length, screens: rows.filter(r => r.isScreen).length, flagged, fixed });

    out.push(`## ${role} — ${rows.length} files, ${flagged} with remaining risk, ${fixed} touched in this branch`, '');
    out.push('| Screen | Type | Remaining risk | Phase 1 |', '|---|---|---|---|');
    for (const r of rows) {
        out.push(`| \`${r.name}\` | ${r.isScreen ? 'screen' : 'component'} | ${r.n === 0 ? 'ok' : Object.entries(r.h).map(([k, v]) => `${k}×${v}`).join(', ')} | ${r.fixed ? '✅ fixed' : '—'} |`);
    }
    out.push('');
}

out.splice(2, 0,
    '',
    '| Role | Files | Screens | Remaining risk | Touched |',
    '|---|---|---|---|---|',
    ...summary.map(s => `| ${s.role} | ${s.total} | ${s.screens} | ${s.flagged} | ${s.fixed} |`),
    `| **total** | **${grandFiles}** | | **${grandFlagged}** | **${grandFixed}** |`,
);

mkdirSync('docs', { recursive: true });
writeFileSync(join('docs', 'SCREEN_INVENTORY.md'), out.join('\n'), 'utf8');
console.log(`docs/SCREEN_INVENTORY.md — ${grandFiles} files, ${grandFlagged} with remaining risk, ${grandFixed} touched`);
